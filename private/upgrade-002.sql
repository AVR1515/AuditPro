CREATE TABLE IF NOT EXISTS attachments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 test_id BIGINT UNSIGNED NULL, action_id BIGINT UNSIGNED NULL,
 uploaded_by BIGINT UNSIGNED NOT NULL, filename VARCHAR(180) NOT NULL,
 mime VARCHAR(100) NOT NULL, bytes INT UNSIGNED NOT NULL, sha256 CHAR(64) NOT NULL,
 content MEDIUMBLOB NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT attachment_parent CHECK ((test_id IS NULL) <> (action_id IS NULL)),
 FOREIGN KEY(test_id) REFERENCES tests(id), FOREIGN KEY(action_id) REFERENCES actions(id),
 FOREIGN KEY(uploaded_by) REFERENCES users(id)
) ENGINE=InnoDB;
