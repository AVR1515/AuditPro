CREATE TABLE IF NOT EXISTS auditable_units (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(180) NOT NULL UNIQUE, process_name VARCHAR(180) NOT NULL,
 accountable VARCHAR(180) NOT NULL, cycle_months SMALLINT UNSIGNED NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS risk_assessments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, unit_id BIGINT UNSIGNED NOT NULL,
 assessor_id BIGINT UNSIGNED NOT NULL, methodology VARCHAR(32) NOT NULL,
 likelihood TINYINT UNSIGNED NOT NULL, impact TINYINT UNSIGNED NOT NULL,
 score TINYINT UNSIGNED NOT NULL, rating ENUM('bajo','medio','alto','critico') NOT NULL,
 rationale TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(unit_id) REFERENCES auditable_units(id),
 FOREIGN KEY(assessor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_assessment_links (
 audit_id BIGINT UNSIGNED PRIMARY KEY, assessment_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(audit_id) REFERENCES audits(id),
 FOREIGN KEY(assessment_id) REFERENCES risk_assessments(id)
) ENGINE=InnoDB;
