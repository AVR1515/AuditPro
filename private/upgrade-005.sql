CREATE TABLE IF NOT EXISTS annual_plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 plan_year SMALLINT UNSIGNED NOT NULL, revision INT UNSIGNED NOT NULL,
 reason TEXT NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 approved_by BIGINT UNSIGNED NULL, approved_at TIMESTAMP NULL DEFAULT NULL,
 UNIQUE(plan_year,revision),
 FOREIGN KEY(created_by) REFERENCES users(id), FOREIGN KEY(approved_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS annual_plan_items (
 plan_id BIGINT UNSIGNED NOT NULL, audit_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL, entity VARCHAR(180) NOT NULL, risk VARCHAR(20) NOT NULL,
 owner_name VARCHAR(160) NOT NULL, original_status VARCHAR(20) NOT NULL,
 PRIMARY KEY(plan_id,audit_id),
 FOREIGN KEY(plan_id) REFERENCES annual_plans(id), FOREIGN KEY(audit_id) REFERENCES audits(id)
) ENGINE=InnoDB;
