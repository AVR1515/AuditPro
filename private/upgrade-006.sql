CREATE TABLE IF NOT EXISTS audit_schedule (
 audit_id BIGINT UNSIGNED PRIMARY KEY,
 start_on DATE NOT NULL, end_on DATE NOT NULL, planned_minutes INT UNSIGNED NOT NULL,
 FOREIGN KEY(audit_id) REFERENCES audits(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_time (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 audit_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 worked_on DATE NOT NULL, minutes SMALLINT UNSIGNED NOT NULL,
 description VARCHAR(180) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(audit_id) REFERENCES audits(id), FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX user_workday(user_id,worked_on)
) ENGINE=InnoDB;
